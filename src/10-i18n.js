/* ============ i18n — French default, English toggle. Zero hardcoded strings in screens. ============ */
const I18N = (() => {
  const dict = { fr: {}, en: {} };
  let lang = 'fr';
  function t(key, params) {
    let s = dict[lang][key] ?? dict.fr[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll('{' + k + '}', v);
    return s;
  }
  // FR uses the singular for 0 <= n < 2 ("0 jour", "1,5 unité"); EN only for exactly 1
  function plural(key, n, params) {
    const one = lang === 'fr' ? Math.abs(n) < 2 : Math.abs(n) === 1;
    return t(key + (one ? '_one' : '_many'), { n, ...params });
  }
  return {
    t, plural,
    get lang() { return lang; },
    set lang(l) { lang = dict[l] ? l : 'fr'; },
    extend(part) { for (const l of Object.keys(part)) { dict[l] = dict[l] || {}; Object.assign(dict[l], part[l]); } },
  };
})();
